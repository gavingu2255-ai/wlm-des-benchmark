def load_scores():
    rows=[]
    for f in sorted(os.listdir(RES)):
        if not f.endswith('.csv'): continue
        for r in csv.DictReader(open(os.path.join(RES,f), encoding='utf-8')):
            r['_file']=f; rows.append(r)
    return rows

def clean(rows, judge='claude'):
    out=[]
    for r in rows:
        if r.get(f'{judge}_parse_error')=='True': continue
        if not r.get(f'{judge}_hallucination'): continue
        out.append(r)
    return out

def exp_of(r):
    e=r.get('experiment') or ''
    if e: return e
    t=r['task_id']
    if t in E1: return 'exp1'
    if int(t[1:])<=37: return 'exp2'
    return 'exp3'

