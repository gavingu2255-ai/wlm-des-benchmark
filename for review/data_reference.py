def sha(path):
    return hashlib.sha256(open(path,'rb').read()).hexdigest()[:16]

def bootstrap_d(a, b, seed=42, n=5000):
    import numpy as np
    p=((st.stdev(a)**2+st.stdev(b)**2)/2)**0.5 if len(a)>1 and len(b)>1 else 0
    d=(st.mean(a)-st.mean(b))/p if p else 0.0
    rng=np.random.default_rng(seed); A=np.array(a); B=np.array(b); ds=np.empty(n)
    for i in range(n):
        sa=rng.choice(A,A.size,True); sb=rng.choice(B,B.size,True)
        pp=((sa.var(ddof=1)+sb.var(ddof=1))/2)**0.5
        ds[i]=0.0 if pp==0 else (sa.mean()-sb.mean())/pp
    return d, float(np.percentile(ds,2.5)), float(np.percentile(ds,97.5))

